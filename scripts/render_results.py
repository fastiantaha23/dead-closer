"""Render bench/results/*.json into RESULTS.md (the human-readable benchmark report)."""
from __future__ import annotations

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
R = os.path.join(ROOT, "bench", "results")
NAMES = {"full": "Full agent", "no_followups": "No follow-ups", "no_qualification": "No qualification questions",
         "slow_response": "Human-speed first reply (4 h)"}


def pm(x, scale=1.0, nd=1, suffix=""):
    return f"{x[0] * scale:.{nd}f}{suffix} ±{x[1] * scale:.{nd}f}"


def main() -> None:
    sim = json.load(open(os.path.join(R, "simulation.json"), encoding="utf-8"))
    saf = json.load(open(os.path.join(R, "safety.json"), encoding="utf-8"))
    sq, sc = sim["speed_quiet"], sim["speed_under_contention"]
    L = ["# Benchmark results", "",
         "Generated by `python -m bench.simulate`, `python -m bench.safety_suite` and `scripts/render_results.py`. "
         f"Backend: **{saf['backend']}** (offline rules engine, deterministic; no LLM calls).", "",
         "## 1. Speed (measured)", "",
         f"First-reply latency, {sim['speed_quiet']['leads']} sequential new leads on an idle machine ({sim['speed_quiet']['backend']}); "
         "this is the whole engine: LangGraph, checkpointer, SQLite, NLU, safety guards, rendering:", "",
         "| p50 | p95 | p99 | worst | within 60 s SLA |", "|---|---|---|---|---|",
         f"| {sq['p50_ms']} ms | {sq['p95_ms']} ms | {sq['p99_ms']} ms | {sq['max_ms']} ms | {sq['within_60s_pct']}% |", "",
         f"Inside the 12 simulation runs (6 processes sharing one laptop CPU, so inflated by contention) the first reply was p50 {sc['p50_ms'][0]:.0f} ms, "
         f"p95 {sc['p95_ms'][0]:.0f} ms, p99 {sc['p99_ms'][0]:.0f} ms, worst {sc['max_ms']} ms, {sc['within_60s_pct']}% within 60 s.", ""]
    lt = sim["load_test"]
    L += [f"Burst load test: **{lt['concurrent_leads']} simultaneous new leads** (+ a reply each) on {lt['backend']} with {lt['workers']} workers: "
          f"sustained {lt['leads_per_second']} new-lead conversations/s (one instance, 32 client threads, single short burst - do not extrapolate to hourly volume without a soak test), first reply p50 {lt['first_reply_ms']['p50']} ms, p95 {lt['first_reply_ms']['p95']} ms, "
          f"p99 {lt['first_reply_ms']['p99']} ms, max {lt['first_reply_ms']['max']} ms, {lt['within_60s_pct']}% within the SLA.", "",
          "All 300 leads of the burst were answered inside the SLA; the queue is serialized by SQLite + the GIL, so the burst p95 is the time to drain the queue. "
          "With the Claude backend enabled add model latency per call (understand + compose, so two calls per message; not measured here). "
          "Run `DEADCLOSER_LLM=claude python -m bench.simulate --perf` to measure it with your key.", "",
          "## 2. Understanding the lead (measured against ground truth)", "",
          "Accuracy is scored only where the simulated lead actually stated the value in its message "
          "(typos, ranges, slang, '450k', '$450,000', 'about 8 weeks', 'just browsing'...). Phrase pools were written independently of the agent's patterns.", "",
          "| Field | Accuracy | n |", "|---|---|---|",
          f"| Budget (within 5%) | {pm(sim['extraction']['budget_accuracy'], 100, 1, '%')} | {sim['extraction']['budget_n']} |",
          f"| Timeline (within max(7 d, 40%)) | {pm(sim['extraction']['timeline_accuracy'], 100, 1, '%')} | {sim['extraction']['timeline_n']} |",
          f"| 'Just browsing' detected | {pm(sim['extraction']['browsing_detection'], 100, 1, '%')} | {sim['extraction']['browsing_n']} |", "",
          "## 3. Conversion and revenue (simulated leads - read the caveat)", "",
          f"{sim['leads_per_run']} leads per run, seeds {sim['seeds']}, 35 virtual days, real scheduler. Mean ± std over seeds.", "",
          "| Variant | Booking rate | Revenue / 100 leads | Billable share of bookings | Bookings after a follow-up | Low-intent leads billed / booked |",
          "|---|---|---|---|---|---|"]
    for k in ("full", "no_followups", "no_qualification", "slow_response"):
        v = sim["variants"][k]
        L.append(f"| {NAMES[k]} | {pm(v['booking_rate'], 100, 1, '%')} | ${v['revenue_per_100_leads_usd'][0]:.0f} | "
                 f"{v['billable_share_of_bookings'][0] * 100:.0f}% | {v['bookings_after_followup_pct'][0]:.0f}% | "
                 f"{v['billable_from_low_intent_leads'][0]:.1f} / {v['bookings_from_low_intent_leads'][0]:.1f} |")
    L += ["", "**What to take from it:** follow-ups and fast replies add bookings; removing qualification adds *unqualified* visits but they are "
          "not billable, so revenue falls (the billing guard removes any incentive to pad visits).", "",
          "\"Low-intent\" counts the browser, price-sensitive, disinterested and adversarial personas. Browsers who book are never billed (0 of 5 in seed 1, see below); "
          "the billed ones are almost all price-sensitive leads whose stated budget fits a cheaper listing, which the billing rule treats as qualified - "
          "arguably genuine buyers, so read that column as an upper bound on false billing.", "",
          "**Caveat:** lead behaviour (reply/booking probabilities per persona, and that a 4-hour reply loses 60% of leads) is *assumed*, so "
          "absolute booking rates are illustrative. Assumptions are in `bench/simulate.py` (`PERSONAS`, `SLOW_PENALTY`) and `simulation.json`. "
          "The comparison between variants uses identical simulated leads and is the useful signal. Real performance must be measured in a pilot.", "",
          "Per-persona outcome (seed 1):", "", "| Persona | Leads | Booked | Billable |", "|---|---|---|---|"]
    for p, s in sim["detail_seed1"]["by_persona"].items():
        L.append(f"| {p} | {s['leads']} | {s['booked']} | {s['billable']} |")
    pb = sim["detail_seed1"]["playbook"]
    L += ["", "Follow-up playbook the real-estate tenant accumulated in long-term memory (seed 1). **This demonstrates the mechanism, not a benefit:** in the "
          "simulation a lead's chance to reply does not depend on the angle, so there is nothing for the bandit to learn and the spread is noise "
          "(`checkin` is higher only because it is the first touch). The UCB selection pays off only if real leads respond differently to different angles.", "",
          "| Angle | Tries | Replies | Rate |", "|---|---|---|---|"]
    for a, s in sorted(pb.items(), key=lambda x: -x[1]["reply_rate"]):
        L.append(f"| {a} | {s['tries']} | {s['wins']} | {s['reply_rate'] * 100:.0f}% |")
    c = sim["compliance"]
    L += ["", "## 4. Compliance counters inside the simulation (worst over seeds)", "",
          f"- Messages sent after a lead opted out: **{c['messages_after_opt_out']}**",
          f"- Proactive messages outside 9:00-20:00 local: **{c['proactive_outside_window']}**",
          f"- Max / median messages sent to one lead in 35 days: {c['max_outbound_per_lead']} / {c['median_outbound_per_lead']}",
          f"- Leads that opted out: {c['opted_out_leads']}; handed to a human: {c['handed_to_human']}", "",
          f"## 5. Safety suite: {saf['passed']}/{saf['total']} ({saf['pass_rate'] * 100:.1f}%)", "",
          "| Category | Passed |", "|---|---|"]
    for k, v in saf["by_category"].items():
        L.append(f"| {k.replace('_', ' ')} | {v['passed']}/{v['total']} |")
    L += ["", "**Honest notes on the safety score.** The suite was written alongside the agent. Its first run scored 92/100 and found real bugs "
          "(PII was redacted *before* it was detected so it was never audited; two escalation phrasings were missed; a password-request produced "
          "a false PII warning) - all fixed, and tests added. A later end-to-end test caught a default business address leaking another tenant's name "
          "(the output guard blocked it; the default was removed). Because decisions are code and the LLM only words a plan, prompt-injection "
          "resistance here is structural; with the Claude backend the same suite should be re-run (`DEADCLOSER_LLM=claude python -m bench.safety_suite`) "
          "- that run has **not** been performed for this report. Passing 100% of your own tests is not a guarantee against unseen attacks; treat it as a regression gate.", ""]
    open(os.path.join(ROOT, "RESULTS.md"), "w", encoding="utf-8").write("\n".join(L))
    print("wrote RESULTS.md")


if __name__ == "__main__":
    main()
